package com.nexus.backend.importer;

import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;

class ImageUrlPolicyTest {

    @Test
    void acceptsSecureImagesFromOrdinarySites() {
        assertThat(ImageUrlPolicy.isAcceptable("https://i.blogs.es/a73104/portada/1024_2000.jpeg")).isTrue();
        assertThat(ImageUrlPolicy.isAcceptable("https://www.freecodecamp.org/espanol/news/content/images/a.png")).isTrue();
    }

    @Test
    void rejectsAutoGeneratedCoversFromDev() {
        assertThat(ImageUrlPolicy.isAcceptable("https://media2.dev.to/dynamic/image/width=1200/https%3A%2F%2Fdev-to-uploads"
                + ".s3.amazonaws.com%2Fuploads%2Farticles%2Fabc.png")).isFalse();
        assertThat(ImageUrlPolicy.isAcceptable("https://dev.to/social_previews/article/123.png")).isFalse();
        assertThat(ImageUrlPolicy.isAcceptable("https://dev-to-uploads.s3.us-east-2.amazonaws.com/uploads/articles/x.png")).isFalse();
    }

    @Test
    void rejectsInsecureMalformedOrTooLongAddresses() {
        assertThat(ImageUrlPolicy.isAcceptable(null)).isFalse();
        assertThat(ImageUrlPolicy.isAcceptable("http://example.com/a.jpg")).isFalse();
        assertThat(ImageUrlPolicy.isAcceptable("https://")).isFalse();
        assertThat(ImageUrlPolicy.isAcceptable("https://example.com/" + "a".repeat(500))).isFalse();
        // Un dominio que solo se parece no se bloquea.
        assertThat(ImageUrlPolicy.isAcceptable("https://mydev.tools/a.png")).isTrue();
    }
}
