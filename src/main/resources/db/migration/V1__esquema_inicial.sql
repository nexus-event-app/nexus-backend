-- Esquema inicial de Nexus. Compatible con PostgreSQL (producción) y H2 (desarrollo y tests).
-- Los enums se guardan como VARCHAR sin CHECK: los valores los valida la aplicación, y así añadir
-- uno nuevo no requiere migración.

create table users (
    id bigint generated by default as identity,
    name varchar(50) not null,
    email varchar(100) not null,
    password varchar(255) not null,
    role varchar(20) not null,
    enabled boolean default true not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint pk_users primary key (id),
    constraint uk_users_email unique (email)
);

create table news (
    id bigint generated by default as identity,
    title varchar(200) not null,
    content text,
    source_url varchar(500),
    image_url varchar(500),
    author varchar(100),
    category varchar(30) not null,
    is_active boolean,
    source varchar(100),
    external_id varchar(200),
    created_at timestamp(6) not null,
    updated_at timestamp(6),
    constraint pk_news primary key (id),
    constraint uk_news_external_id unique (external_id)
);

create index idx_news_created_at on news (created_at);
create index idx_news_category on news (category);
create index idx_news_is_active on news (is_active);

create table job_offers (
    id bigint generated by default as identity,
    title varchar(200) not null,
    company varchar(120) not null,
    description text not null,
    location varchar(120) not null,
    work_mode varchar(20) not null,
    contract_type varchar(20) not null,
    level varchar(20) not null,
    tags varchar(400),
    apply_url varchar(500) not null,
    source varchar(100),
    external_id varchar(200),
    is_active boolean not null,
    published_at timestamp(6) not null,
    expires_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6),
    constraint pk_job_offers primary key (id),
    constraint uk_job_offers_external_id unique (external_id)
);

create index idx_jobs_created_at on job_offers (created_at);
create index idx_jobs_is_active on job_offers (is_active);
create index idx_jobs_level on job_offers (level);
create index idx_jobs_work_mode on job_offers (work_mode);
create index idx_jobs_expires_at on job_offers (expires_at);

create table discussions (
    id bigint generated by default as identity,
    title varchar(200) not null,
    content text not null,
    category varchar(30) not null,
    user_id bigint,
    is_active boolean not null,
    likes_count integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6),
    constraint pk_discussions primary key (id),
    constraint fk_discussions_user foreign key (user_id) references users (id)
);

create index idx_discussions_created_at on discussions (created_at);
create index idx_discussions_category on discussions (category);
create index idx_discussions_is_active on discussions (is_active);
create index idx_discussions_author on discussions (user_id);

create table comments (
    id bigint generated by default as identity,
    content text not null,
    discussion_id bigint,
    user_id bigint,
    likes_count integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6),
    constraint pk_comments primary key (id),
    constraint fk_comments_discussion foreign key (discussion_id) references discussions (id),
    constraint fk_comments_user foreign key (user_id) references users (id)
);

create index idx_comments_discussion on comments (discussion_id);
create index idx_comments_author on comments (user_id);
create index idx_comments_created_at on comments (created_at);

create table discussion_likes (
    id bigint generated by default as identity,
    discussion_id bigint not null,
    user_id bigint not null,
    created_at timestamp(6) not null,
    constraint pk_discussion_likes primary key (id),
    constraint uk_discussion_likes_discussion_user unique (discussion_id, user_id),
    constraint fk_discussion_likes_discussion foreign key (discussion_id) references discussions (id),
    constraint fk_discussion_likes_user foreign key (user_id) references users (id)
);

create index idx_discussion_likes_user on discussion_likes (user_id);

create table comment_likes (
    id bigint generated by default as identity,
    comment_id bigint not null,
    user_id bigint not null,
    created_at timestamp(6) not null,
    constraint pk_comment_likes primary key (id),
    constraint uk_comment_likes_comment_user unique (comment_id, user_id),
    constraint fk_comment_likes_comment foreign key (comment_id) references comments (id),
    constraint fk_comment_likes_user foreign key (user_id) references users (id)
);

create index idx_comment_likes_user on comment_likes (user_id);

create table testimonials (
    id bigint generated by default as identity,
    name varchar(100) not null,
    role varchar(100),
    location varchar(100),
    content varchar(300) not null,
    user_id bigint,
    is_active boolean,
    is_pending boolean,
    is_highlighted boolean,
    created_at timestamp(6) not null,
    updated_at timestamp(6),
    constraint pk_testimonials primary key (id),
    constraint fk_testimonials_user foreign key (user_id) references users (id)
);

create index idx_testimonials_created_at on testimonials (created_at);
create index idx_testimonials_user on testimonials (user_id);

create table import_sources (
    id bigint generated by default as identity,
    name varchar(100) not null,
    type varchar(30) not null,
    url varchar(500) not null,
    news_category varchar(30),
    auto_publish boolean not null,
    active boolean not null,
    remote_only boolean not null,
    keywords varchar(500),
    interval_minutes integer not null,
    last_run_at timestamp(6),
    last_status varchar(20),
    last_message varchar(500),
    last_imported_count integer,
    created_at timestamp(6) not null,
    updated_at timestamp(6),
    constraint pk_import_sources primary key (id),
    constraint uk_import_sources_name unique (name)
);

create table import_exclusions (
    external_id varchar(200) not null,
    created_at timestamp(6) not null,
    constraint pk_import_exclusions primary key (external_id)
);
