-- Etapas de las rutas de aprendizaje que cada persona marca como hechas. El contenido de las rutas vive en el
-- frontend; aquí solo se guardan sus identificadores («frontend» / «javascript»).
create table learning_progress (
    id bigint generated by default as identity,
    user_id bigint not null,
    path_id varchar(40) not null,
    step_id varchar(40) not null,
    completed_at timestamp(6) not null,
    constraint pk_learning_progress primary key (id),
    constraint uk_learning_progress_step unique (user_id, path_id, step_id),
    constraint fk_learning_progress_user foreign key (user_id) references users (id) on delete cascade
);
