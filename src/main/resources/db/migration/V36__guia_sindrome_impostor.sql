## What impostor syndrome is

It is the feeling that **you don’t deserve what you have achieved**: that your successes are down to luck, to someone helping you or to it being “no big deal”, and that at some point someone will discover you are not as good as they think.

It was described by psychologists Pauline Clance and Suzanne Imes in 1978. Although it is called a “syndrome”, **it is not an illness or a diagnosis**: it is a way of thinking about yourself that, with practice, can change.

## It is not just you

Studies estimate that **between 9% and 82% of people** experience it at some point, depending on how it is measured, and it affects men and women equally. It does not go away with years of experience either: many senior people still feel it when they change company, technology or role.

In other words: that person on your team who seems to know everything has probably also felt, at some point, that they were not good enough.

## Why it is so common in tech

The tech sector has several things that feed it:

- **There is always something new to learn.** Languages, frameworks and tools change all the time, and it is impossible to keep up with everything.
- **It is a huge field.** Nobody masters frontend, backend, databases, security and deployment all at once.
- **You see other people’s results, not their process.** LinkedIn and GitHub only show finished projects, not the hours of errors behind them.
- **You often work alone** or remotely, without seeing that others get stuck too.

## How to recognise it

You may be dealing with impostor syndrome if:

- You think your successes are **a matter of luck**.
- You find it hard to accept a **compliment** about your work.
- You don’t dare to **ask questions** in case people find out you don’t know something.
- You constantly **compare yourself** with people who have been working for years.
- You don’t apply for jobs because **you don’t meet 100% of the requirements**.
- You go over your code again and again before showing it, hoping it will be **perfect**.

Naming it is already the first step: when the little voice shows up, you can tell yourself “oh, it’s you again”.

## What you can do

- **Write down your wins.** Create a document, a note or a `wins.md` file and write down what you achieve: a bug you fixed, something you learned, a compliment you received. When you doubt yourself, read it. Facts beat feelings.
- **Compare yourself with who you were a few months ago**, not with people who have ten years of experience. Look at your first project: you would surely do it much better now.
- **Ask.** Asking doesn’t show that you don’t know: it shows that you want to learn. Experienced people ask lots of questions, they just do it without apologising.
- **Ask for specific feedback.** Instead of imagining what people think of your work, ask: “what would you improve in this part?”. Reality is almost always kinder than what you imagine.
- **Accept that not knowing is part of the job.** Looking things up in the documentation or online is not cheating: it is what everyone who codes does, every day.
- **Find a mentor** or someone with more experience to talk to. Hearing that it happened to them too helps enormously.
- **Swap “perfect” for “done”.** A published project with flaws teaches more than a perfect one you never finish.
- **Apply for jobs** even if you don’t meet every requirement. Requirement lists are a wish list, not an exam.

## When it shows up, remember

- Nobody knows everything, not even people who have been doing this for years.
- If you were chosen, it is because **someone saw something in you**.
- Feeling like an impostor is often a sign that **you are growing** and stepping out of your comfort zone.
- Your doubts are not evidence: they are just a feeling.

