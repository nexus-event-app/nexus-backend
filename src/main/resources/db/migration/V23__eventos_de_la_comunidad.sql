-- Eventos que comparte la comunidad (charlas, meetups, hackathons...). Se publican al momento; los pasados dejan de
-- mostrarse solos y se borran pasados unos meses. Quién lo compartió no se muestra en la web.
create table community_events (
    id bigint generated by default as identity,
    title varchar(120) not null,
    description varchar(280) not null,
    url varchar(500) not null,
    starts_on date not null,
    start_time time,
    mode varchar(15) not null,
    city varchar(80),
    for_women boolean default false not null,
    is_active boolean default true not null,
    user_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6),
    constraint pk_community_events primary key (id),
    constraint fk_community_events_user foreign key (user_id) references users (id)
);

create index idx_community_events_upcoming on community_events (is_active, starts_on);
create index idx_community_events_user on community_events (user_id, created_at);
