Es completamente normal sentirse así. Casi todo el mundo pasa por ese momento de vértigo al terminar. La buena noticia es que no tienes que tenerlo todo resuelto mañana: solo necesitas un plan y dar pasos pequeños cada semana. En esta guía te contamos cuáles.

## 1. Date unos días y haz balance

Antes de lanzarte a enviar currículums, para un momento. Repasa lo que has aprendido y pregúntate:

- ¿Qué parte disfruté más: el frontend, el backend, las bases de datos…?
- ¿Qué proyecto del bootcamp me siento capaz de explicar con orgullo?
- ¿Qué conceptos todavía me cuestan?

Apúntalo. Esa lista será tu brújula para decidir qué estudiar y qué tipo de ofertas buscar.

## 2. No dejes de programar (aunque sea poco)

El mayor riesgo después de un bootcamp es dejar de practicar. Lo que no usas se olvida rápido. No hace falta programar ocho horas al día: **es mejor una hora diaria que un día entero a la semana**.

Algunas ideas:

- Retoma un proyecto del bootcamp y mejóralo: añade pruebas, mejora el diseño o súbelo a internet.
- Haz pequeños retos de programación para mantener la lógica en forma.
- Sigue una de nuestras [rutas de aprendizaje](/rutas) para avanzar con orden y sin perderte.

## 3. Construye un portfolio que hable por ti

Cuando no tienes experiencia laboral, tu portfolio es tu carta de presentación. Más vale **un proyecto terminado y bien explicado que cinco a medias**.

Un buen proyecto de portfolio:

- **Resuelve un problema real**, aunque sea pequeño o tuyo.
- **Se puede probar sin instalar nada**: está publicado en internet.
- **Tiene un buen README**: qué hace, con qué tecnologías, capturas y qué aprendiste.
- **Su código está en GitHub**, ordenado y con commits que se entienden.

Si no sabes qué proyecto hacer, pregunta en el [foro](/foro): seguro que alguien de la comunidad te da ideas.

## 4. Cuida tu GitHub y tu LinkedIn

Muchas empresas te buscarán antes de llamarte. Haz que lo que encuentren juegue a tu favor:

- **GitHub:** fija tus mejores proyectos, añade una foto y una breve presentación.
- **LinkedIn:** pon un titular claro (por ejemplo, «Desarrolladora web junior | React · Java»), cuenta tus proyectos y menciona el bootcamp.
- **Comparte lo que aprendes:** un post contando un proyecto o un problema que resolviste demuestra más que cualquier currículum.

## 5. Sal de casa: ve a eventos y conoce gente

Muchas oportunidades llegan por personas, no por portales de empleo. Ir a **meetups, charlas y hackathons** te ayuda a:

- Aprender de gente que ya trabaja en el sector.
- Practicar a hablar de tecnología, algo que luego agradecerás en las entrevistas.
- Enterarte de ofertas antes de que se publiquen.

Al principio da vergüenza, pero nadie espera que lo sepas todo. En la [agenda de eventos](/eventos) tienes meetups, charlas y hackathons, también de comunidades de mujeres en tech.

## 6. Busca empleo con estrategia, no a ciegas

Enviar cien currículums iguales rara vez funciona. Mejor:

- **Filtra bien:** busca ofertas de prácticas y junior, y no te asustes si no cumples el 100 % de los requisitos. Si cumples buena parte, preséntate.
- **Adapta tu CV** a cada oferta: destaca lo que encaja.
- **Lleva un registro** de dónde te has presentado y en qué punto está cada proceso.
- **Prepara las entrevistas técnicas:** repasa los fundamentos y practica explicar tus proyectos en voz alta.

En [Empleo](/empleo) reunimos prácticas y ofertas junior, y puedes guardarlas para revisarlas con calma.

## 7. Aprende a convivir con los «no»

Vas a recibir rechazos, y procesos en los que nadie te contesta. **No significa que no valgas**: significa que estás en el camino. Cada entrevista, incluso las que salen mal, te prepara para la siguiente.

Celebra los pequeños avances: terminar un proyecto, pasar una primera llamada, entender por fin ese concepto que se te resistía.

## 8. No lo hagas sola ni solo

Lo más difícil de terminar un bootcamp no es lo técnico: es sentir que de repente estás sola o solo. Rodearte de gente que está en tu mismo punto lo cambia todo: compartís dudas, recursos, ofertas… y ánimos.

Para eso nace [Primer Commit](/registro): una comunidad gratuita donde encontrar eventos, ofertas junior y un foro donde ninguna pregunta es tonta.

