Es normal sentir todo eso. La buena noticia es que una entrevista técnica se puede preparar, y mucho. En esta guía te contamos cómo suelen ser y qué hacer antes, durante y después.

## 1. Entiende cómo es el proceso

Cada empresa tiene su forma de hacerlo, pero la mayoría de procesos para perfiles junior siguen un camino parecido:

- **Llamada inicial:** una conversación corta con alguien de selección para conocerte, tu motivación y tus condiciones.
- **Prueba técnica:** un ejercicio para casa, un test en línea o un pequeño reto en directo.
- **Entrevista técnica:** hablas con alguien del equipo sobre tu prueba, tus proyectos y conceptos básicos.
- **Entrevista final:** a veces con la persona responsable del equipo, para ver si encajáis.

Cuando te llamen, pregunta sin problema cuántas fases tiene el proceso y qué tipo de prueba vas a hacer. Es una pregunta habitual y te ayudará a prepararte mejor.

## 2. Investiga la empresa y la oferta

Antes de la entrevista, dedica un rato a conocer la empresa:

- ¿A qué se dedica y qué productos tiene?
- ¿Qué tecnologías aparecen en la oferta?
- ¿Tiene blog técnico, perfil en GitHub o charlas en eventos?

Apunta las tecnologías de la oferta que conoces y las que no. Las que conoces, repásalas; las que no, mira al menos qué son. Si alguna palabra te suena a chino, búscala en nuestro [glosario](/glosario).

## 3. Repasa los fundamentos

A un perfil junior no se le pide saberlo todo, pero sí tener claras las bases. Según tu perfil, repasa:

- **Fundamentos del lenguaje:** variables, tipos, funciones, bucles, arrays y objetos.
- **Programación orientada a objetos**, si trabajas con Java o similares: clases, herencia e interfaces.
- **Web:** qué es HTTP, qué es una API REST y qué pasa cuando escribes una dirección en el navegador.
- **Bases de datos:** consultas SQL básicas y para qué sirve cada tipo de base de datos.
- **Git:** commit, rama, merge y pull request.

No hace falta memorizar definiciones: **es mucho mejor entender los conceptos y saber explicarlos con tus palabras**.

## 4. Prepara tus proyectos para contarlos

Casi seguro que te pedirán que hables de algún proyecto. Elige uno o dos y prepárate para explicar:

- **Qué problema resuelve** y para quién.
- **Con qué tecnologías lo hiciste** y por qué las elegiste.
- **Qué fue lo más difícil** y cómo lo resolviste.
- **Qué mejorarías** si tuvieras más tiempo.

Practica contándolo en voz alta, en dos o tres minutos. Contar los problemas que te encontraste y cómo los superaste dice mucho de cómo trabajas.

## 5. Afronta la prueba técnica con método

Si la prueba es para casa:

- **Lee bien el enunciado** y pregunta si algo no queda claro.
- **Entrega algo que funcione** antes de añadir extras.
- **Cuida el código:** nombres claros, ordenado y con un README que explique cómo probarlo.
- **Respeta el plazo.** Si necesitas más tiempo, avisa con antelación.

Si la prueba es en directo:

- **Piensa en voz alta:** cuenta qué estás pensando hacer y por qué. Importa tanto cómo razonas como el resultado.
- **Empieza por una solución sencilla** y mejórala después.
- **Si te atascas, dilo:** «ahora mismo no recuerdo cómo se hace esto, pero lo buscaría así…» es una respuesta perfectamente válida.

## 6. Prepara también la parte personal

Las entrevistas no son solo técnicas. Prepara respuestas sinceras para preguntas como:

- «Háblame de ti.»
- «¿Por qué quieres trabajar en tecnología?»
- «¿Por qué te interesa esta empresa?»
- «Cuéntame alguna vez que te equivocaras y qué aprendiste.»

Si vienes de otro sector, **cuéntalo como un valor**: lo que aprendiste allí (trato con clientes, organización, trabajo en equipo…) también suma.

## 7. Lleva tus propias preguntas

Al final casi siempre te preguntarán: «¿Tienes alguna pregunta?». Tener alguna preparada demuestra interés. Por ejemplo:

- ¿Cómo es un día normal en el equipo?
- ¿Qué tecnologías usáis en el día a día?
- ¿Habrá alguien que me acompañe al empezar?
- ¿Qué esperáis de una persona junior los primeros meses?

## 8. Cuida los detalles del día

- **Si es en línea:** prueba la cámara, el micrófono y la conexión antes. Busca un sitio tranquilo y con buena luz.
- **Si es presencial:** mira cómo llegar y sal con tiempo de sobra.
- **Ten a mano** tu CV, la oferta y unas notas con lo que quieres contar.
- **Respira.** Al otro lado hay personas que también tuvieron su primera entrevista.

## 9. Después de la entrevista

- **Envía un mensaje breve de agradecimiento** si tienes el contacto: suma más de lo que parece.
- **Apunta lo que te preguntaron** y lo que te costó responder. Es tu lista de repaso para la siguiente.
- **Si no sale, pide opinión.** No siempre te la darán, pero cuando lo hacen es muy valiosa.

Y recuerda: cada entrevista, salga como salga, te deja mejor preparada o preparado para la siguiente.

## 10. Practica con la comunidad

La mejor forma de perder los nervios es practicar. Haz simulacros con alguien de confianza, cuenta tus proyectos en voz alta y comparte tu experiencia en el [foro](/foro): seguro que alguien ha pasado por un proceso parecido y te puede dar pistas.

En los [eventos](/eventos) también puedes conocer a gente que ya trabaja en el sector y preguntarle cómo son las entrevistas en su empresa.

