-- Reportes de la comunidad: cualquier persona con cuenta puede avisar de una discusión, un comentario o un
-- testimonio que incumpla las normas. El equipo los revisa agrupados por contenido en el panel de administración.
create table reports (
    id bigint generated by default as identity,
    reporter_id bigint not null,
    target_type varchar(20) not null,
    target_id bigint not null,
    reason varchar(30) not null,
    details varchar(500),
    status varchar(20) not null,
    resolution varchar(20),
    resolved_by bigint,
    resolved_at timestamp(6),
    created_at timestamp(6) not null,
    constraint pk_reports primary key (id),
    -- Cada persona reporta cada contenido una sola vez.
    constraint uk_reports_reporter_target unique (reporter_id, target_type, target_id),
    constraint fk_reports_reporter foreign key (reporter_id) references users (id) on delete cascade,
    constraint fk_reports_resolved_by foreign key (resolved_by) references users (id) on delete set null
);

create index idx_reports_status on reports (status, target_type, target_id);
create index idx_reports_target on reports (target_type, target_id);
