-- Ofertas de empleo que cada usuario guarda para revisar más tarde. Privadas: solo las ve su dueño.
-- Al borrar una oferta (o un usuario) se borran también sus guardados.
create table saved_jobs (
    id bigint generated by default as identity,
    user_id bigint not null,
    job_id bigint not null,
    created_at timestamp(6) not null,
    constraint pk_saved_jobs primary key (id),
    constraint uk_saved_jobs_user_job unique (user_id, job_id),
    constraint fk_saved_jobs_user foreign key (user_id) references users (id) on delete cascade,
    constraint fk_saved_jobs_job foreign key (job_id) references job_offers (id) on delete cascade
);

create index idx_saved_jobs_job on saved_jobs (job_id);
