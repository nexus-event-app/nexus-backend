-- Mejor respuesta: quien abre una discusión puede marcar el comentario que le resolvió la duda.
-- Si se borra ese comentario, la discusión vuelve a quedar sin resolver.
alter table discussions add column accepted_comment_id bigint;
alter table discussions add constraint fk_discussions_accepted_comment
    foreign key (accepted_comment_id) references comments (id) on delete set null;

-- Avisos para cada persona: alguien responde a su discusión o marcan su respuesta como la mejor.
-- Al borrar la persona, la discusión o el comentario, se borran también sus avisos.
create table notifications (
    id bigint generated by default as identity,
    recipient_id bigint not null,
    actor_id bigint not null,
    type varchar(30) not null,
    discussion_id bigint not null,
    comment_id bigint,
    read_at timestamp(6),
    created_at timestamp(6) not null,
    constraint pk_notifications primary key (id),
    constraint fk_notifications_recipient foreign key (recipient_id) references users (id) on delete cascade,
    constraint fk_notifications_actor foreign key (actor_id) references users (id) on delete cascade,
    constraint fk_notifications_discussion foreign key (discussion_id) references discussions (id) on delete cascade,
    constraint fk_notifications_comment foreign key (comment_id) references comments (id) on delete cascade
);

-- La campanita pregunta a menudo cuántos avisos sin leer hay: índice por destinatario y estado.
create index idx_notifications_recipient on notifications (recipient_id, read_at, created_at);
create index idx_notifications_discussion on notifications (discussion_id);
create index idx_notifications_comment on notifications (comment_id);
