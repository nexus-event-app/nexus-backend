-- Verificación de email y recuperación de contraseña.

alter table users add column email_verified_at timestamp(6);
-- Fecha del último cambio de contraseña: los JWT emitidos antes dejan de valer.
alter table users add column credentials_changed_at timestamp(6);

-- Las cuentas que ya existían se consideran verificadas para no bloquearlas.
update users set email_verified_at = created_at;

-- Tokens de un solo uso enviados por email. Solo se guarda el hash SHA-256 del token, nunca el token.
create table user_tokens (
    id bigint generated by default as identity,
    user_id bigint not null,
    type varchar(30) not null,
    token_hash varchar(64) not null,
    expires_at timestamp(6) not null,
    used_at timestamp(6),
    created_at timestamp(6) not null,
    constraint pk_user_tokens primary key (id),
    constraint uk_user_tokens_token_hash unique (token_hash),
    constraint fk_user_tokens_user foreign key (user_id) references users (id) on delete cascade
);

create index idx_user_tokens_user_type on user_tokens (user_id, type);
create index idx_user_tokens_expires_at on user_tokens (expires_at);
